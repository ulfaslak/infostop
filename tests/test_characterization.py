"""Characterization tests: pin the labels the pipeline produces on fixed traces.

Labels are compared up to relabelling, because label integers are arbitrary and
Infomap versions may number modules differently. `-1` positions must match.
"""

import infomap
import numpy as np
import pytest

from infostop import Infostop, SpatialInfomap

INFOMAP_VERSION = tuple(int(x) for x in infomap.__version__.split(".")[:2])

# Degrees per meter, roughly, at the latitudes used below
DEG = 1 / 111_000


def _visit(rng, center, t0, scale, n=15, dt=60):
    """`n` points scattered around `center`, one every `dt` seconds from `t0`."""
    xy = center + rng.normal(0, scale, size=(n, 2))
    return np.column_stack([xy, t0 + dt * np.arange(n)])


def _travel(start, end, t0, n=5, dt=60):
    """`n` evenly spaced points strictly between `start` and `end`."""
    frac = np.linspace(0, 1, n + 2)[1:-1, None]
    xy = start + frac * (end - start)
    return np.column_stack([xy, t0 + dt * np.arange(n)])


def _itinerary(rng, places, unit):
    """Visit each place in `places` in turn, travelling between them."""
    places = [np.asarray(p, dtype=float) for p in places]
    segments, t = [], 0
    for i, place in enumerate(places):
        segments.append(_visit(rng, place, t, scale=2 * unit))
        t = segments[-1][-1, 2] + 60
        if i + 1 < len(places):
            segments.append(_travel(place, places[i + 1], t))
            t = segments[-1][-1, 2] + 60
    return np.vstack(segments)


def _places(metric):
    """Named places, about 1 km apart, in the units of `metric`."""
    if metric == "haversine":
        unit, origin = DEG, np.array([55.70, 12.50])
    else:
        unit, origin = 1.0, np.array([0.0, 0.0])
    offsets = {
        "home_a": (0, 0),
        "home_b": (0, 1000),
        "work": (1000, 0),
        "shop": (1000, 1000),
        "cafe": (-1000, 0),
    }
    return unit, {k: origin + unit * np.array(v) for k, v in offsets.items()}


def single_user_trace(metric):
    rng = np.random.default_rng(0)
    unit, p = _places(metric)
    route = ["home_a", "work", "home_a", "shop", "home_a", "work", "home_a"]
    return _itinerary(rng, [p[k] for k in route], unit)


def multi_user_traces(metric):
    rng = np.random.default_rng(1)
    unit, p = _places(metric)
    routes = [
        ["home_a", "work", "home_a", "cafe", "home_a"],
        ["home_b", "work", "shop", "home_b"],
        ["home_b", "cafe", "home_b", "work", "home_b"],
    ]
    return [_itinerary(rng, [p[k] for k in r], unit) for r in routes]


def chain_points(metric):
    """A line of points 8 units apart: with `r2=10` each links only to its neighbours.

    Infomap must split this into several modules, so the result depends on
    Infomap's optimizer rather than only on which points are connected.
    """
    unit, p = _places(metric)
    steps = np.arange(40)[:, None] * np.array([8.0, 0.0])
    return p["home_a"] + unit * steps


def _canonical(labels):
    """Relabel in order of first appearance and write one character per point.

    The first label seen becomes `0`, the next `1`, and so on; `-1` becomes `.`.
    """
    symbols = "0123456789abcdefghijklmnopqrstuvwxyz"
    mapping = {}
    return "".join(
        "." if label == -1 else symbols[mapping.setdefault(label, len(mapping))]
        for label in _flatten(labels)
    )


def _flatten(labels):
    """Concatenate per-user label arrays into one list."""
    if isinstance(labels, list):
        return [x for u in labels for x in _flatten(u)]
    return np.asarray(labels).tolist()


def run_cases():
    """Every pinned case, as `{name: labels}`."""
    out = {}
    for metric in ["haversine", "euclidean"]:
        out[f"single_{metric}"] = Infostop(distance_metric=metric).fit_predict(
            single_user_trace(metric)
        )
        out[f"multi_{metric}"] = Infostop(distance_metric=metric).fit_predict(
            multi_user_traces(metric)
        )
        out[f"single_{metric}_weighted"] = Infostop(
            distance_metric=metric, weighted=True
        ).fit_predict(single_user_trace(metric))
        out[f"chain_{metric}"] = SpatialInfomap(distance_metric=metric).fit_predict(
            chain_points(metric)
        )
        out[f"chain_{metric}_weighted"] = SpatialInfomap(
            distance_metric=metric, weighted=True
        ).fit_predict(chain_points(metric))
    return out


